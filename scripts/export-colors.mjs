// Exports the site palette from public/styles.css (plus the code-highlight colours in
// public/notebook.css) to design-tokens/ so other projects can import it.
// Run: npm run colors
import { readFile, writeFile, mkdir } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const css = await readFile(new URL('public/styles.css', root), 'utf8');
const notebook = await readFile(new URL('public/notebook.css', root), 'utf8');

const blockOf = selector => {
  const start = css.indexOf('{', css.indexOf(selector));
  return css.slice(start + 1, css.indexOf('}', start));
};
const tokensIn = block => Object.fromEntries([...block.matchAll(/--color-([\w-]+):\s*(oklch\([^)]*\))/g)].map(m => [m[1], m[2]]));
const light = tokensIn(blockOf(':root {'));
const dark = tokensIn(blockOf(':root[data-theme="dark"]'));

const roles = {
  paper: ['底色', '页面底色'],
  'paper-2': ['底色', '次级底色、悬停'],
  'paper-3': ['底色', '第三层底色、选中、文字选区'],
  surface: ['底色', '卡片和输入框表面'],
  ink: ['文字', '正文和标题'],
  'ink-2': ['文字', '次要文字'],
  muted: ['文字', '日期、说明等辅助文字'],
  rule: ['文字', '分隔线和边框'],
  accent: ['强调', '链接、强调、当前项'],
  'accent-ink': ['强调', '强调色底上的文字'],
  focus: ['强调', '键盘焦点环'],
  sky: ['品牌', '头像后的天空圆盘、引用竖线'],
  sun: ['品牌', '主按钮（向日葵）'],
  'sun-ink': ['品牌', '主按钮上的文字'],
  ring: ['品牌', '头像描边'],
  'tile-oi': ['磁贴', '「算法竞赛」磁贴'],
  'tile-notebook': ['磁贴', '「算法板子」磁贴'],
  'tile-materials': ['磁贴', '「学习资料」磁贴'],
};

// OKLCH -> sRGB hex (nearest in-gamut value, channels clipped).
function oklchToHex(value) {
  const [l, c, h] = value.match(/[\d.]+/g).map(Number);
  const L = l / 100, a = c * Math.cos(h * Math.PI / 180), b = c * Math.sin(h * Math.PI / 180);
  const l_ = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m_ = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s_ = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linear = [
    4.0767416621 * l_ - 3.3077115913 * m_ + 0.2309699292 * s_,
    -1.2684380046 * l_ + 2.6097574011 * m_ - 0.3413193965 * s_,
    -0.0041960863 * l_ - 0.7034186147 * m_ + 1.707614701 * s_,
  ];
  return '#' + linear.map(v => {
    v = Math.min(1, Math.max(0, v));
    const g = v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055;
    return Math.round(g * 255).toString(16).padStart(2, '0');
  }).join('');
}

const palette = Object.keys(light).map(name => ({
  name,
  group: roles[name]?.[0] ?? '其他',
  role: roles[name]?.[1] ?? '',
  light: { oklch: light[name], hex: oklchToHex(light[name]) },
  dark: { oklch: dark[name] ?? light[name], hex: oklchToHex(dark[name] ?? light[name]) },
}));

// Syntax colours are plain hex in notebook.css: light rule first, dark rule second.
const syntax = ['keyword', 'number', 'string', 'comment', 'directive'].map(kind => {
  const [lightHex, darkHex] = [...notebook.matchAll(new RegExp(`\\.syntax-${kind}\\{color:(#[0-9a-f]{6})`, 'g'))].map(m => m[1]);
  return { name: `syntax-${kind}`, light: lightHex, dark: darkHex };
});

const pick = (theme, format) => palette.map(t => [t.name, t[theme][format]]);
const decls = (pairs, indent = '  ') => pairs.map(([n, v]) => `${indent}--color-${n}: ${v};`).join('\n');
const syntaxPairs = theme => syntax.map(s => [s.name, s[theme]]);
const header = '/* yangjm.cn palette · generated by scripts/export-colors.mjs */\n';

const cssFile = `${header}/* Light is the default; dark applies with the OS setting or data-theme="dark". */
:root {
${decls(pick('light', 'oklch'))}
${decls(syntaxPairs('light'))}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decls(pick('dark', 'oklch'), '    ')}
${decls(syntaxPairs('dark'), '    ')}
  }
}
:root[data-theme="dark"] {
${decls(pick('dark', 'oklch'))}
${decls(syntaxPairs('dark'))}
}
`;

const hexCss = cssFile.replaceAll(/oklch\([^)]*\)/g, v => oklchToHex(v));

const tailwind = `${header}/* Tailwind CSS v4: @import "tailwindcss"; then this file. Gives bg-paper, text-ink, border-rule ... */
@theme {
${decls(pick('light', 'oklch'))}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${decls(pick('dark', 'oklch'), '    ')}
  }
}
:root[data-theme="dark"] {
${decls(pick('dark', 'oklch'))}
}
`;

const scss = `// yangjm.cn palette · generated by scripts/export-colors.mjs (hex, sRGB)
${palette.map(t => `$${t.name}: ${t.light.hex};\n$${t.name}-dark: ${t.dark.hex};`).join('\n')}
${syntax.map(s => `$${s.name}: ${s.light};\n$${s.name}-dark: ${s.dark};`).join('\n')}
`;

const json = JSON.stringify({ source: 'https://yangjm.cn', palette, syntax }, null, 2) + '\n';

const out = new URL('design-tokens/', root);
await mkdir(out, { recursive: true });
await Promise.all([
  writeFile(new URL('colors.css', out), cssFile),
  writeFile(new URL('colors.hex.css', out), hexCss),
  writeFile(new URL('tailwind.css', out), tailwind),
  writeFile(new URL('_colors.scss', out), scss),
  writeFile(new URL('colors.json', out), json),
]);
console.log(`Exported ${palette.length} palette tokens and ${syntax.length} syntax colours to design-tokens/`);
